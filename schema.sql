-- ============================================================
-- Segurança (Supabase): tabelas do schema "public" ficam expostas na API REST
-- pública do projeto (chave "anon"). Ativar RLS sem criar políticas bloqueia
-- esse acesso; o app conecta como dono das tabelas (postgres) e não é afetado.
-- ============================================================
ALTER TABLE tipo_veiculo ENABLE ROW LEVEL SECURITY;
ALTER TABLE evento       ENABLE ROW LEVEL SECURITY;
ALTER TABLE local        ENABLE ROW LEVEL SECURITY;
ALTER TABLE movimentacao ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- View de saldo atual (ocupação = entradas - saídas) por evento e área.
-- security_invoker: a view respeita o RLS acima (PostgreSQL 15+).
-- ============================================================
DROP VIEW IF EXISTS vw_ocupacao;
CREATE VIEW vw_ocupacao WITH (security_invoker = true) AS
SELECT
    l.evento_id,
    m.local_id,
    m.tipo_veiculo_id,
    SUM(CASE WHEN m.movimentacao = 'entrada' THEN 1 ELSE -1 END) AS ocupados
FROM movimentacao m
JOIN local l ON l.id = m.local_id
GROUP BY l.evento_id, m.local_id, m.tipo_veiculo_id;
