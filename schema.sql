-- ============================================================
-- Vaguinha - Schema PostgreSQL (Supabase)
-- ============================================================
-- Pode ser executado mais de uma vez (idempotente):
--   * banco vazio            → cria tudo + evento "Corrida da FAB" com 13 áreas;
--   * banco da versão antiga → (sem eventos) migra as 13 áreas e todo o
--                              histórico para o evento "Corrida da FAB".
-- ============================================================

-- Tipos de veículo
CREATE TABLE IF NOT EXISTS tipo_veiculo (
    id   SMALLINT PRIMARY KEY,       -- 1 = Carro, 2 = Moto
    nome VARCHAR(20) NOT NULL
);

INSERT INTO tipo_veiculo (id, nome) VALUES (1, 'Carro'), (2, 'Moto')
ON CONFLICT (id) DO NOTHING;

-- Eventos (ex.: "Corrida da FAB")
CREATE TABLE IF NOT EXISTS evento (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(80) NOT NULL,
    criado_em TIMESTAMP   NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Sao_Paulo')
);

-- Áreas de cada evento (a tabela se chama "local" por compatibilidade)
CREATE TABLE IF NOT EXISTS local (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id INTEGER     NOT NULL REFERENCES evento(id) ON DELETE CASCADE,
    nome      VARCHAR(60) NOT NULL,
    cor       VARCHAR(20) NOT NULL DEFAULT '#1f6f8b',
    cap_carro INTEGER     NOT NULL DEFAULT 0 CHECK (cap_carro >= 0),
    cap_moto  INTEGER     NOT NULL DEFAULT 0 CHECK (cap_moto >= 0),
    ordem     INTEGER     NOT NULL DEFAULT 0
);

-- Movimentação (histórico de entradas e saídas)
CREATE TABLE IF NOT EXISTS movimentacao (
    id              BIGSERIAL PRIMARY KEY,
    tipo_veiculo_id SMALLINT    NOT NULL REFERENCES tipo_veiculo(id),
    local_id        INTEGER     NOT NULL REFERENCES local(id) ON DELETE CASCADE,
    movimentacao    VARCHAR(10) NOT NULL CHECK (movimentacao IN ('entrada','saida')),
    horario         TIMESTAMP   NOT NULL DEFAULT (NOW() AT TIME ZONE 'America/Sao_Paulo')
);

-- ============================================================
-- Migração da versão antiga (áreas fixas 1..13, sem eventos)
-- ============================================================
DO $$
DECLARE
    v_evento INTEGER;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'local' AND column_name = 'evento_id'
    ) THEN
        DROP VIEW IF EXISTS vw_ocupacao;  -- depende das colunas alteradas abaixo

        INSERT INTO evento (nome) VALUES ('Corrida da FAB') RETURNING id INTO v_evento;

        ALTER TABLE local ADD COLUMN evento_id INTEGER REFERENCES evento(id) ON DELETE CASCADE;
        ALTER TABLE local ADD COLUMN cor   VARCHAR(20) NOT NULL DEFAULT '#1f6f8b';
        ALTER TABLE local ADD COLUMN ordem INTEGER     NOT NULL DEFAULT 0;
        UPDATE local SET
            evento_id = v_evento,
            ordem     = id,
            cor       = CASE WHEN id <= 4 THEN '#1f6f8b'
                             WHEN id <= 8 THEN '#2e6b3e'
                             ELSE '#5b4b8a' END;
        ALTER TABLE local ALTER COLUMN evento_id SET NOT NULL;

        -- id das áreas passa a ser gerado automaticamente (para criar novas)
        ALTER TABLE movimentacao DROP CONSTRAINT IF EXISTS movimentacao_local_id_fkey;
        ALTER TABLE local        ALTER COLUMN id       TYPE INTEGER;
        ALTER TABLE movimentacao ALTER COLUMN local_id TYPE INTEGER;
        ALTER TABLE local ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        PERFORM setval(pg_get_serial_sequence('local', 'id'),
                       (SELECT COALESCE(MAX(id), 0) + 1 FROM local), false);
        ALTER TABLE movimentacao ADD CONSTRAINT movimentacao_local_id_fkey
            FOREIGN KEY (local_id) REFERENCES local(id) ON DELETE CASCADE;
    END IF;
END $$;

-- Horário no fuso de Brasília (o servidor do Supabase roda em UTC)
ALTER TABLE movimentacao
    ALTER COLUMN horario SET DEFAULT (NOW() AT TIME ZONE 'America/Sao_Paulo');

CREATE INDEX IF NOT EXISTS idx_local_evento   ON local (evento_id);
CREATE INDEX IF NOT EXISTS idx_mov_local_tipo ON movimentacao (local_id, tipo_veiculo_id);

